import { expect, test } from '@playwright/test'
import { openApp, tap, waitForGameText, collectConsoleErrors } from './smoke-helpers.js'

test('a player can author and fly low and high pickups', async ({page}) => {
  const errors = collectConsoleErrors(page)
  await openApp(page)
  await tap(page.locator('#hangar-btn'))
  await tap(page.locator('#hangar-group-meta'))
  await tap(page.locator('#hangar-tab-editor'))
  await expect(page.locator('#editor-play')).toBeInViewport({ratio:1})
  const height = page.locator('#editor-height')
  await expect(height).toBeDisabled()
  await tap(page.locator('#editor-palette').getByRole('button', {name:'⭐ Star'}))
  await expect(height).toBeEnabled()
  const canvas = page.locator('#editor-canvas')
  await canvas.scrollIntoViewIfNeeded()
  const box = await canvas.boundingBox()
  await height.selectOption('14')
  await canvas.click({position:{x:box.width * .35,y:box.height * .35}})
  await expect(page.locator('#editor-status')).toContainText('14m high')
  await height.selectOption('6')
  await canvas.click({position:{x:box.width * .65,y:box.height * .65}})
  await expect(page.locator('#editor-status')).toContainText('6m high')
  await height.selectOption('10')
  await canvas.focus()
  await canvas.press('ArrowUp')
  await expect(page.locator('#editor-status')).toContainText('Cursor')
  await canvas.press('Enter')
  await expect(page.locator('#editor-status')).toContainText('10m high')
  await tap(page.locator('#editor-play'))
  await waitForGameText(page)
  await expect.poll(()=>page.evaluate(()=>JSON.parse(window.render_game_to_text()).fairness.visibleStars.map(star=>star.y).sort((a,b)=>a-b))).toEqual([6,10,14])
  expect(errors).toEqual([])
})
